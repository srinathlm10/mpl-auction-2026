// Builds supabase/seed.sql from src/data/*.json, plus supabase/setup-all.sql
// (schema + auction + seed in one file).
// Usage: npm run seed:generate
import { readFileSync, writeFileSync } from "node:fs";

const read = (name) => JSON.parse(readFileSync(`src/data/${name}.json`, "utf8"));
const data = { sports: read("sports"), teams: read("teams"), players: read("players") };

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v === null || v === undefined ? "null" : String(v));

const lines = [
  "-- Sample data for the MPL site (generated by scripts/generate-seed.mjs).",
  "-- Run AFTER schema.sql and auction.sql. Re-running wipes and reloads the sample rows.",
  "",
  "do $$",
  "begin",
  "  if to_regclass('public.auction_state') is null then",
  "    raise exception 'Run supabase/schema.sql, then supabase/auction.sql, before this file (seed.sql).';",
  "  end if;",
  "end $$;",
  "",
  "truncate public.players, public.teams, public.sports restart identity cascade;",
  "",
  "-- squad_size is added by auction.sql, so run auction.sql before this file.",
  "insert into public.sports (id, name, slug, squad_size) overriding system value values",
  data.sports.map((s) => `  (${s.id}, ${q(s.name)}, ${q(s.slug)}, ${s.squad_size})`).join(",\n") + ";",
  "",
  "insert into public.teams (id, name, sport_id, logo_url, captain, total_purse) overriding system value values",
  data.teams.map((t) => `  (${t.id}, ${q(t.name)}, ${t.sport_id}, ${q(t.logo_url)}, ${q(t.captain)}, ${t.total_purse})`).join(",\n") + ";",
  "",
  "-- Teams' remaining_purse is recalculated by trigger when players are inserted.",
  "insert into public.players (id, name, sport_id, batch, role_or_position, skills, attributes, photo_url, base_price, status, team_id, sold_price) overriding system value values",
  data.players
    .map(
      (p) =>
        `  (${p.id}, ${q(p.name)}, ${p.sport_id}, ${q(p.batch)}, ${q(p.role_or_position)}, ${q(JSON.stringify(p.skills))}::jsonb, ${q(JSON.stringify(p.attributes ?? {}))}::jsonb, ${q(p.photo_url)}, ${p.base_price}, ${q(p.status)}, ${n(p.team_id)}, ${n(p.sold_price)})`,
    )
    .join(",\n") + ";",
  "",
  "-- The truncate above also clears the live auction state (it references sports); recreate it.",
  "insert into public.auction_state (id) values (1) on conflict (id) do nothing;",
  "",
  "-- Keep identity counters ahead of the explicit ids used above.",
  "select setval(pg_get_serial_sequence('public.sports', 'id'),  (select max(id) from public.sports));",
  "select setval(pg_get_serial_sequence('public.teams', 'id'),   (select max(id) from public.teams));",
  "select setval(pg_get_serial_sequence('public.players', 'id'), (select max(id) from public.players));",
  "",
];

writeFileSync("supabase/seed.sql", lines.join("\n"));
console.log("Wrote supabase/seed.sql");

// One-paste setup for a new project: schema + auction + seed, in the right order.
const part = (file) => `-- ===== ${file} =====\n\n` + readFileSync(`supabase/${file}`, "utf8").trim() + "\n";
writeFileSync(
  "supabase/setup-all.sql",
  [
    "-- MPL – complete database setup (generated by scripts/generate-seed.mjs; do not edit by hand).",
    "-- Paste this whole file into a NEW query in Supabase -> SQL Editor and click Run.",
    "-- Safe to re-run; re-running reloads the sample players and clears auction results.",
    "",
    part("schema.sql"),
    part("auction.sql"),
    part("seed.sql"),
  ].join("\n"),
);
console.log("Wrote supabase/setup-all.sql");
